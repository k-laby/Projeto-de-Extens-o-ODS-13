-- 3. Visões (views)
-- ---------------------------------------------------------------------
-- Reproduz exatamente as colunas do df_final.csv
CREATE VIEW vw_df_final AS
SELECT m.ibge                              AS IBGE,
       CONCAT(m.nome, ' (', m.uf, ')')     AS Cidade,
       md.nome                             AS Modal,
       e.ano                               AS Ano,
       e.co2_t                             AS CO2_t,
       p.populacao                         AS Populacao,
       e.co2_t / p.populacao               AS CO2_por_habitante
FROM emissao e
JOIN municipio m  ON m.ibge = e.ibge
JOIN modal md     ON md.id_modal = e.id_modal
JOIN populacao p  ON p.ibge = e.ibge AND p.ano = e.ano;

-- Indicador total municipal: soma dos três modais ÷ população
CREATE VIEW vw_total_municipio_ano AS
SELECT m.ibge,
       m.nome                              AS cidade,
       e.ano,
       SUM(e.co2_t)                        AS co2_total_t,
       p.populacao,
       SUM(e.co2_t) / p.populacao          AS co2_total_por_habitante
FROM emissao e
JOIN municipio m  ON m.ibge = e.ibge
JOIN populacao p  ON p.ibge = e.ibge AND p.ano = e.ano
GROUP BY m.ibge, m.nome, e.ano, p.populacao;

