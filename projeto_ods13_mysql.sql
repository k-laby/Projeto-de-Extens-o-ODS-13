-- ---------------------------------------------------------------------
-- 1. Tabelas
-- ---------------------------------------------------------------------
CREATE TABLE municipio (
  ibge  INT          NOT NULL COMMENT 'Código IBGE do município (7 dígitos)',
  nome  VARCHAR(60)  NOT NULL,
  uf    CHAR(2)      NOT NULL,
  PRIMARY KEY (ibge)
) ENGINE=InnoDB;

CREATE TABLE modal (
  id_modal  TINYINT      NOT NULL,
  nome      VARCHAR(30)  NOT NULL,
  PRIMARY KEY (id_modal),
  UNIQUE KEY uq_modal_nome (nome)
) ENGINE=InnoDB;

CREATE TABLE populacao (
  ibge       INT       NOT NULL,
  ano        SMALLINT  NOT NULL,
  populacao  INT       NOT NULL COMMENT 'Habitantes (pacote brpop / IBGE)',
  PRIMARY KEY (ibge, ano),
  CONSTRAINT fk_populacao_municipio FOREIGN KEY (ibge) REFERENCES municipio (ibge),
  CONSTRAINT ck_populacao_positiva CHECK (populacao > 0)
) ENGINE=InnoDB;

CREATE TABLE emissao (
  ibge      INT       NOT NULL,
  id_modal  TINYINT   NOT NULL,
  ano       SMALLINT  NOT NULL,
  co2_t     DOUBLE    NOT NULL COMMENT 'Emissão de CO2 em toneladas por ano',
  PRIMARY KEY (ibge, id_modal, ano),
  CONSTRAINT fk_emissao_municipio  FOREIGN KEY (ibge)          REFERENCES municipio (ibge),
  CONSTRAINT fk_emissao_modal      FOREIGN KEY (id_modal)      REFERENCES modal (id_modal),
  CONSTRAINT fk_emissao_populacao  FOREIGN KEY (ibge, ano)     REFERENCES populacao (ibge, ano),
  CONSTRAINT ck_emissao_nao_negativa CHECK (co2_t >= 0)
) ENGINE=InnoDB;

